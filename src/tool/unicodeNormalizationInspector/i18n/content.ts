function localizedFaq(
  values: string[],
): { question: string; answer: string }[] {
  return Array.from({ length: 4 }, (_, index) => ({
    question: values[index * 2]!,
    answer: values[index * 2 + 1]!,
  }));
}

function localizedHowTo(values: string[]): { name: string; text: string }[] {
  return Array.from({ length: 4 }, (_, index) => ({
    name: values[index * 2]!,
    text: values[index * 2 + 1]!,
  }));
}

export function createContent(
  locale: Locale,
): ToolLocaleContent<UnicodeNormalizationInspectorUI> {
  if (locale === "en") return englishContent;
  const copy = translations[locale];
  const seo = copy.seo;
  const faq = localizedFaq(copy.faq);
  const howTo = localizedHowTo(copy.howTo);
  const faqSchema: WithContext<FAQPage> = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faq.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: { "@type": "Answer", text: item.answer },
    })),
  };
  const howToSchema: WithContext<HowTo> = {
    "@context": "https://schema.org",
    "@type": "HowTo",
    name: copy.title,
    description: copy.description,
    step: howTo.map((step, index) => ({
      "@type": "HowToStep",
      position: index + 1,
      name: step.name,
      text: step.text,
    })),
  };
  const appSchema: WithContext<SoftwareApplication> = {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: copy.title,
    description: copy.description,
    applicationCategory: "DeveloperApplication",
    operatingSystem: "All",
    offers: { "@type": "Offer", price: "0", priceCurrency: "EUR" },
    inLanguage: locale,
  };
  return {
    slug: copy.slug,
    title: copy.title,
    description: copy.description,
    ui: ui(copy.ui),
    faqTitle: copy.faqTitle,
    faq,
    bibliographyTitle: copy.bibliographyTitle,
    bibliography,
    howTo,
    schemas: [appSchema, faqSchema, howToSchema],
    seo: [
      { type: "title", text: seo[0]!, level: 2 },
      { type: "paragraph", html: seo[1]! },
      { type: "title", text: seo[2]!, level: 2 },
      { type: "paragraph", html: seo[3]! },
      {
        type: "table",
        headers: tables[locale]![0]!,
        rows: tables[locale]!.slice(1),
      },
      { type: "title", text: seo[4]!, level: 2 },
      { type: "list", items: seo[5]!.split("|") },
      { type: "tip", title: seo[6]!, html: seo[7]! },
      { type: "diagnostic", variant: "warning", title: seo[8]!, html: seo[9]! },
    ],
  };
}
